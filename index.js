// Efeito de scroll no navbar
window.addEventListener('scroll', function() {
  const navbar = document.querySelector('.navbar');
  if (window.scrollY > 50) {
    navbar.classList.add('scrolled');
  } else {
    navbar.classList.remove('scrolled');
  }
});

// Inicializar tooltips
var tooltipTriggerList = [].slice.call(document.querySelectorAll('[data-bs-toggle="tooltip"]'));
var tooltipList = tooltipTriggerList.map(function (tooltipTriggerEl) {
  return new bootstrap.Tooltip(tooltipTriggerEl);
});

// Ativar animações quando elementos entram na viewport
const animateOnScroll = function() {
  const elements = document.querySelectorAll('.activity-card, .pet-pillar');
  
  elements.forEach(element => {
    const elementPosition = element.getBoundingClientRect().top;
    const screenPosition = window.innerHeight / 1.3;
    
    if (elementPosition < screenPosition) {
      element.style.opacity = '1';
      element.style.transform = 'translateY(0)';
    }
  });
};

// Definir estado inicial para animação
window.addEventListener('DOMContentLoaded', function() {
  const elements = document.querySelectorAll('.activity-card, .pet-pillar');
  elements.forEach(element => {
    element.style.opacity = '0';
    element.style.transform = 'translateY(20px)';
    element.style.transition = 'opacity 0.5s ease, transform 0.5s ease';
  });
  
  // Disparar uma vez no carregamento
  animateOnScroll();
});

// Observar scroll para animações
window.addEventListener('scroll', animateOnScroll);